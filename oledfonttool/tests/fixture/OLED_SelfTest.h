/*
 * 整屏显示一次。
 *
 * 定位命令自己发（0xB0|页、列地址高低 4 位），不调用 OLED_SetCursor，
 * 只依赖【适配区】指向的那两个最底层的函数。
 *
 * 用法：
 *     1) 本文件放到 OLED.c 所在目录（比如 Hardware\）
 *     2) main.c 里 #include "OLED_SelfTest.h"
 *     3) OLED_Init();
 *        OLED_SelfTest_Show();
 *        while (1);
 */
static void OLED_SelfTest_Show(void)
{
	uint8_t page, col;

	for (page = 0; page < OLED_SELFTEST_PAGES; page++)
	{
		OLED_SELFTEST_WRITE_CMD((uint8_t)(0xB0 | (page & 0x07)));
		OLED_SELFTEST_WRITE_CMD((uint8_t)(0x10 | ((OLED_SELFTEST_COL_OFFSET >> 4) & 0x0F)));
		OLED_SELFTEST_WRITE_CMD((uint8_t)(0x00 | (OLED_SELFTEST_COL_OFFSET & 0x0F)));

		for (col = 0; col < OLED_SELFTEST_W; col++)
		{
			OLED_SELFTEST_WRITE_DATA(OLED_SelfTest[page][col]);
		}
	}
}

